    @Test
    fun matchesEcmaScriptToString() {
        val failures = ArrayList<String>()
        for ((bits, js) in table) {
            val d = Double.fromBits(bits)
            val actual = TreeSerializer.formatNumber(d)
            if (actual != js) {
                failures.add(
                    "formatNumber(0x%016x) == \"%s\", JS String(x) == \"%s\"".format(bits, actual, js)
                )
            }
        }
        assertEquals(emptyList<String>(), failures, "ECMAScript Number::toString divergences")
    }

    /** The traps that a naive `Double.toString` passthrough would fall into. */
    @Test
    fun doesNotLeakJavaDoubleToStringFormatting() {
        assertEquals("125", TreeSerializer.formatNumber(125.0))       // Java: "125.0"
        assertEquals("10000000000000000", TreeSerializer.formatNumber(1e16)) // Java: "1.0E16"
        assertEquals("1e+21", TreeSerializer.formatNumber(1e21))      // Java: "1.0E21"
        assertEquals("1e-7", TreeSerializer.formatNumber(1e-7))       // Java: "1.0E-7"
        assertEquals("0.000001", TreeSerializer.formatNumber(1e-6))   // Java: "1.0E-6"
        assertEquals("0", TreeSerializer.formatNumber(-0.0))          // Java: "-0.0"
        assertEquals("0.1", TreeSerializer.formatNumber(0.1))
    }

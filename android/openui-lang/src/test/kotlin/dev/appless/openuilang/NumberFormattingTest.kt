/**
 * Differential sweep of [TreeSerializer.formatNumber] against ECMAScript
 * `String(x)` (Number::toString, radix 10).
 *
 * This is the SAME 267-entry table the Swift port is verified against
 * (`ios/Packages/OpenUILang/Tests/OpenUILangTests/NumberFormattingTests.swift`),
 * generated once with Node.js v22 from IEEE-754 bit patterns so no literal
 * parsing sits between the table and the double under test.
 *
 * It matters more on the JVM than in Swift: `Double.toString` is NOT
 * `Number::toString`. Java always emits a decimal point (`"125.0"` vs `"125"`),
 * switches to scientific notation at 1e7 rather than 1e21 (`"1.0E16"` vs
 * `"10000000000000000"`), and spells the exponent `E16` rather than `e+16`.
 * Only the digit STRING transfers — and only because JDK 19+ emits the
 * shortest round-tripping decimal, which is what ECMAScript specifies too.
 *
 * Coverage: powers of two 2^0..2^70 and their +/-1 neighbors (positive, and
 * negative every third exponent), Long.MIN/MAX and neighbors, the 1e21
 * positional/exponential boundary, the 1e-6/1e-7 small boundary, classic
 * non-terminating decimals (0.1, 0.3, 0.1+0.2), subnormals, the largest finite
 * double, a half-integer at 2^52, -0.0, seeded pseudo-random integer mantissas
 * at exponents 50..66 (the band where an Int64 fast path diverges from
 * shortest-round-trip), and every numeric literal exercised by fixture
